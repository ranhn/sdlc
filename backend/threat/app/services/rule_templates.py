def _display_name(elem_type: str) -> str:
    """元素类型小写键名 -> 中文展示名。"""
    mapping = {
        "process": "处理进程",
        "actor": "外部角色",
        "externalentity": "外部实体",
        "datastore": "数据存储",
        "store": "数据存储",
        "flow": "数据流",
        "trustboundary": "信任边界",
        "model": "大语言模型",
        "prompt": "提示词",
        "vectorstore": "向量库",
        "tool": "工具/API",
        "trainingdata": "训练数据",
        "agentconfig": "Agent 配置",
    }
    return mapping.get((elem_type or "").strip().lower(), "元素")


